export const getLifeStyleLabel = (key: string) => {
  return lifestyleOptions[key].label;
};

export const getLifeStyleIcon = (key: string, color: 'blue' | 'white' | 'red' | null) => {
  if (color === null) {
    return lifestyleOptions[key]?.['white'];
  }
  return lifestyleOptions[key]?.[color];
};

export const getLifeStyleValue = (key: string, value: string | number | string[]) => {
  let formattedValue: string = '';

  switch (key) {
    case 'numOfRoommate':
      formattedValue = `${value}명`;
      break;

    case 'wakeUpTime':
    case 'sleepingTime':
    case 'turnOffTime': {
      const time = Number(value);
      const period = time < 12 ? '오전' : '오후';
      const formattedTime = time % 12 === 0 ? 12 : time % 12;
      formattedValue = `${period} ${String(formattedTime).padStart(2, '0')}시`;
      break;
    }

    default:
      formattedValue = String(value);
  }

  // 6글자 이상이면 `...`으로 축약
  return formattedValue !== undefined && formattedValue.length > 6
    ? `${formattedValue.slice(0, 6)}...`
    : formattedValue;
};
